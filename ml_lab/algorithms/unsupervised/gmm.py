"""Gaussian Mixture Model trained with Expectation-Maximisation (EM)."""
import numpy as np
from matplotlib.colors import to_rgb

from ml_lab.core import plotting as P
from ml_lab.core.base import ClusteringDemo
from ml_lab.core.params import Bool, Choice, Int
from ml_lab.core.registry import register


def log_gauss(X, mu, C):
    d = X.shape[1]
    inv = np.linalg.inv(C)
    diff = X - mu
    maha = np.einsum("ij,jk,ik->i", diff, inv, diff)
    return -0.5 * (maha + np.log(np.linalg.det(C)) + d * np.log(2 * np.pi))


class GMM:
    def __init__(self, k=3, cov_type="full", rng=None, reg=1e-4):
        self.k, self.cov_type, self.reg = k, cov_type, reg
        self.rng = rng or np.random.default_rng(0)

    def init(self, X):
        n, d = X.shape
        self.means = X[self.rng.choice(n, self.k, replace=False)].copy()
        self.covs = np.array([np.cov(X.T) / self.k + np.eye(d) * 1e-3] * self.k)
        self.weights = np.full(self.k, 1 / self.k)

    def _log_resp(self, X):
        L = np.column_stack([np.log(w) + log_gauss(X, m, C)
                             for w, m, C in zip(self.weights, self.means, self.covs)])
        mx = L.max(1, keepdims=True)
        lse = mx + np.log(np.exp(L - mx).sum(1, keepdims=True))      # log-sum-exp trick
        return L - lse, float(lse.sum())

    def score(self, X):
        return self._log_resp(X)[1]

    def density(self, X):
        L = np.column_stack([np.log(w) + log_gauss(X, m, C)
                             for w, m, C in zip(self.weights, self.means, self.covs)])
        return np.exp(L).sum(1)

    def steps(self, X, max_iter=100, tol=1e-5):
        self.init(X)
        prev = -np.inf
        n, d = X.shape
        for it in range(max_iter):
            log_r, ll = self._log_resp(X)                 # E-step: soft assignments
            R = np.exp(log_r)
            Nk = R.sum(0) + 1e-10                         # M-step: re-estimate parameters
            self.weights = Nk / n
            self.means = (R.T @ X) / Nk[:, None]
            covs = []
            for j in range(self.k):
                diff = X - self.means[j]
                C = (R[:, j, None] * diff).T @ diff / Nk[j]
                if self.cov_type == "diag":
                    C = np.diag(np.diag(C))
                elif self.cov_type == "spherical":
                    C = np.eye(d) * np.trace(C) / d
                covs.append(C + self.reg * np.eye(d))
            self.covs = np.array(covs)
            yield it, R, ll
            if abs(ll - prev) < tol * abs(ll):
                return
            prev = ll


@register
class GMMDemo(ClusteringDemo):
    name = "Gaussian Mixture (EM)"
    order = 13
    default_dataset = "anisotropic"
    params = [
        Int("n_components", 3, 1, 8),
        Choice("covariance", "full", ["full", "diag", "spherical"],
               help="full = any rotated ellipse, diag = axis-aligned, spherical = circles (~K-Means)."),
        Int("max_iter", 80, 1, 300),
        Bool("show_density", True, help="Contours of the fitted probability density p(x)."),
    ]
    info = """
    ## Idea
    Assume the data was generated by k Gaussian "sources" (each with a mean, covariance and
    weight).  EM alternates:
      E-step: for every point compute the probability it came from each source (soft labels).
      M-step: re-estimate every Gaussian from the points, weighted by those probabilities.
    The log-likelihood never decreases.  Point colours are blended by responsibility -
    points between clusters appear as mixed colours (uncertainty!).

    ## Embedded-engineer view
    It's "soft" K-Means with a covariance per cluster.  The fitted p(x) is a density model:
    great for anomaly detection (a reading with very low p(x) is suspicious) and for sensor
    fusion problems with multi-modal noise.  Also the basis of the classic speaker-ID systems.

    ## Try this
    \u2022 'anisotropic' with full vs spherical covariance: spherical behaves like K-Means and fails.
    \u2022 n_components larger than the true number: extra components share or split clusters.
    \u2022 Change the seed: EM finds local optima, like K-Means.
    """

    def setup_figure(self, fig):
        fig.clear()
        self.fig = fig
        gs = fig.add_gridspec(1, 2, width_ratios=[1.6, 1])
        self.ax = fig.add_subplot(gs[0])
        self.ax_ll = fig.add_subplot(gs[1])

    def run(self, data, p):
        X = data["X"]
        if p.n_components > len(X):
            yield "More components than points"
            return
        gmm = GMM(p.n_components, p.covariance, np.random.default_rng(p.seed))
        cols = np.array([to_rgb(P.color(j)) for j in range(p.n_components)])
        lls = []
        for it, R, ll in gmm.steps(X, p.max_iter):
            lls.append(ll)
            ax = self.ax
            ax.clear()
            if p.show_density:
                P.plot_scalar_field(ax, lambda G: np.log(gmm.density(G) + 1e-12), X,
                                    levels=15, cmap="Greys", alpha=0.35)
            ax.scatter(X[:, 0], X[:, 1], s=16, c=np.clip(R @ cols, 0, 1), zorder=3)
            for j in range(p.n_components):
                P.draw_ellipse(ax, gmm.means[j], gmm.covs[j], P.color(j), lw=2)
                ax.scatter(*gmm.means[j], marker="X", s=200, c=P.color(j), edgecolors="k", zorder=6)
            P.set_limits(ax, X)
            P.style(ax, f"GMM ({p.covariance})  EM iteration {it + 1}")
            P.textbox(ax, "weights\n" + "\n".join(f"  c{j}: {w:.2f}" for j, w in enumerate(gmm.weights)))
            la = self.ax_ll
            la.clear()
            la.plot(np.arange(1, len(lls) + 1), lls, "o-", ms=3, color=P.color(4))
            P.style(la, "Log-likelihood (always increases)", "EM iteration", "log p(X)")
            yield f"EM iteration {it + 1}: log-likelihood {ll:.2f}"
        k, d = p.n_components, X.shape[1]
        n_par = k * d + k - 1 + k * {"full": d * (d + 1) // 2, "diag": d, "spherical": 1}[p.covariance]
        bic = -2 * lls[-1] + n_par * np.log(len(X))
        self.log(f"Final log-likelihood {lls[-1]:.2f}, BIC {bic:.1f} (lower BIC = better model)")
